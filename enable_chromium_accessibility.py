#!/usr/bin/env python3
"""Make Chromium/Electron apps visible to AT-SPI by flagging their launchers.

Chromium builds an accessibility tree only when it believes an assistive
technology is listening, so by default Electron apps expose their window frame
and nothing else -- literally zero children. Passing
--force-renderer-accessibility at launch fixes that.

Why not the global switch: on GNOME/Cinnamon the `org.a11y.Status`
`ScreenReaderEnabled` D-Bus property is bidirectionally coupled to the
`org.gnome.desktop.a11y.applications screen-reader-enabled` GSettings key.
Setting the property makes the settings daemon start Orca (speech, keyboard
grabs); stopping Orca sets the property back to false. There is no state where
the flag is on and no screen reader is running.

This script instead writes per-user copies of each Chromium/Electron .desktop
file into ~/.local/share/applications, with the flag inserted into every Exec
line. Those copies take precedence over /usr/share/applications and the Flatpak
exports by XDG basename lookup, and survive package and Flatpak updates. Nothing
is modified in place.

    python3 enable_chromium_accessibility.py --list      # detect only
    python3 enable_chromium_accessibility.py --dry-run   # show the rewrites
    python3 enable_chromium_accessibility.py             # apply
    python3 enable_chromium_accessibility.py --revert    # remove what it wrote

Only menu, launcher and URL-handler launches are affected. An app started by
hand -- `flatpak run com.vscodium.codium` -- bypasses the .desktop file and gets
no flag. Re-run after installing a new Chromium app.
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import sys
from pathlib import Path

CHROMIUM_ACCESSIBILITY_FLAG = "--force-renderer-accessibility"

USER_APPLICATIONS_DIRECTORY = (
    Path(os.environ.get("XDG_DATA_HOME") or Path.home() / ".local/share") / "applications"
)

GENERATED_MARKER_COMMENT = (
    "# Generated by linux-desktop-mcp enable_chromium_accessibility.py: adds "
    f"{CHROMIUM_ACCESSIBILITY_FLAG} so AT-SPI can read this Chromium/Electron "
    "app. Delete this file to revert to the packaged launcher."
)

# Recognition of our own output keys off this stable token, never the full
# comment: rewording GENERATED_MARKER_COMMENT would otherwise orphan every file
# an earlier version wrote, making them look hand-made and un-revertable.
GENERATED_MARKER_TOKEN = "enable_chromium_accessibility.py"


def is_generated_by_this_script(desktop_file_contents: str) -> bool:
    return GENERATED_MARKER_TOKEN in desktop_file_contents

# Where packaged launchers live, in XDG precedence order. The per-user directory
# is deliberately absent: it is this script's output, not its input.
SYSTEM_APPLICATION_DIRECTORIES: list[Path] = [
    Path("/usr/share/applications"),
    Path("/usr/local/share/applications"),
    Path("/var/lib/flatpak/exports/share/applications"),
    Path.home() / ".local/share/flatpak/exports/share/applications",
    Path("/var/lib/snapd/desktop/applications"),
]

# Files that only ship alongside a Chromium/Electron runtime. The V8 snapshots
# are the strongest signal; Gecko and native toolkits have no equivalent, so
# Firefox is not misdetected.
CHROMIUM_RUNTIME_MARKER_NAMES = {
    "v8_context_snapshot.bin",
    "snapshot_blob.bin",
    "chrome_crashpad_handler",
    "chrome-sandbox",
    "libvk_swiftshader.so",
    "app.asar",
}

MARKER_SEARCH_MAXIMUM_DEPTH = 4

# A native app that merely embeds a browser view ships the same markers inside a
# subdirectory: Zoom, for instance, is a Qt application with CEF under
# /opt/zoom/cef. Its own UI is already accessible through Qt, and its argument
# parser has no reason to accept a Chromium switch, so a marker found under one
# of these directory names does not count.
EMBEDDED_BROWSER_DIRECTORY_NAMES = {"cef", "libcef", "cefsharp", "qtwebengine"}

# Desktop Entry field codes (%U, %F, ...), the Flatpak file-forwarding sentinels
# (@@, @@u) and literal URI arguments all belong after the switch.
ARGUMENT_PLACEHOLDER_PATTERN = re.compile(
    r"^(?:%[a-zA-Z]|@@u?|[a-zA-Z][a-zA-Z0-9+.-]*://.*)$"
)

# Characters the Desktop Entry spec reserves inside an unquoted Exec argument.
# Quoting must use double quotes; single quotes are not valid Exec quoting and
# desktop-file-validate rejects them.
DESKTOP_ENTRY_RESERVED_CHARACTERS = set(" \t\n\"'\\><~|&;$*?#()`")

FLATPAK_APPLICATION_ID_PATTERN = re.compile(r"^[A-Za-z][\w-]*(?:\.[A-Za-z][\w-]*){2,}$")


# --------------------------------------------------------------------------
# Detection
# --------------------------------------------------------------------------

def read_desktop_entry_exec_values(desktop_file_path: Path) -> list[str]:
    """Every Exec= value in the file, including those in Desktop Actions."""
    try:
        contents = desktop_file_path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return []
    return [line[len("Exec="):] for line in contents.splitlines() if line.startswith("Exec=")]


def split_exec_value(exec_value: str) -> list[str]:
    """Tokenise an Exec value, tolerating the spec's quoting."""
    import shlex

    try:
        return shlex.split(exec_value)
    except ValueError:
        return exec_value.split()


def find_flatpak_application_files_root(command_tokens: list[str]) -> Path | None:
    """For a `flatpak run ... <app-id>` command, locate the app's files/ tree."""
    candidate_identifiers = [
        token for token in command_tokens if FLATPAK_APPLICATION_ID_PATTERN.match(token)
    ]
    installation_roots = [
        Path("/var/lib/flatpak/app"),
        Path.home() / ".local/share/flatpak/app",
    ]
    # Search the last identifier first: `--command=` options precede the app id.
    for application_identifier in reversed(candidate_identifiers):
        for installation_root in installation_roots:
            files_root = installation_root / application_identifier / "current/active/files"
            if files_root.is_dir():
                return files_root
    return None


def lowercaseTrunc(name: str) -> str:
    """Normalize a string of any case to the same consistent truncated lower case"""
    return re.sub(r"[-_./\\#+ ]", "", name).lower()
    

def find_native_program_roots(command_tokens: list[str]) -> list[Path]:
    """Directories worth searching for a non-Flatpak launcher's runtime files."""
    if not command_tokens:
        return []

    program_path_text = shutil.which(command_tokens[0]) or command_tokens[0]
    program_path = Path(program_path_text)
    try:
        program_path = program_path.resolve()
    except OSError:
        pass

    if not program_path.exists():
        return []

    search_roots = [program_path.parent]

    paths = (Path("/usr/lib"), Path("/usr/lib64"), Path("/opt"))
    launchers = dict(
        map(
            lambda p: (p, dict(map(
                lambda d: (lowercaseTrunc(d), p / d), 
                [d for d in os.listdir(p) if (p / d).is_dir]
            ))), 
            paths
        )
    )
    
    # Distro packages commonly put the wrapper in /usr/bin and the runtime in
    # /usr/lib/<name> or /opt/<name>.
    for library_parent in paths:
        candidate = library_parent / program_path.name

        launcher = launchers[library_parent].get(lowercaseTrunc(candidate.name))
        if launcher is not None:
            search_roots.append(launcher)
            continue

    return search_roots


def directory_contains_chromium_runtime(search_root: Path) -> bool:
    """True if a Chromium/Electron runtime marker sits within a few levels."""
    root_depth = len(search_root.parts)
    try:
        for current_directory, subdirectory_names, file_names in os.walk(
            search_root, followlinks=False
        ):
            # Do not descend into an embedded browser runtime.
            subdirectory_names[:] = [
                name
                for name in subdirectory_names
                if name.lower() not in EMBEDDED_BROWSER_DIRECTORY_NAMES
            ]
            if Path(current_directory).name.lower() in EMBEDDED_BROWSER_DIRECTORY_NAMES:
                continue
            if CHROMIUM_RUNTIME_MARKER_NAMES & set(file_names):
                return True
            if len(Path(current_directory).parts) - root_depth >= MARKER_SEARCH_MAXIMUM_DEPTH:
                subdirectory_names.clear()
    except OSError:
        return False
    return False


def is_chromium_launcher(desktop_file_path: Path) -> bool:
    exec_values = read_desktop_entry_exec_values(desktop_file_path)
    if not exec_values:
        return False

    command_tokens = split_exec_value(exec_values[0])
    if not command_tokens:
        return False

    if Path(command_tokens[0]).name == "flatpak":
        flatpak_files_root = find_flatpak_application_files_root(command_tokens)
        search_roots = [flatpak_files_root] if flatpak_files_root else []
    else:
        search_roots = find_native_program_roots(command_tokens)

    return any(directory_contains_chromium_runtime(root) for root in search_roots)


def discover_chromium_launchers(excluded_patterns: list[str] | None = None) -> list[Path]:
    """Packaged .desktop files whose program ships a Chromium/Electron runtime.

    Deduplicated by basename, keeping the first hit in XDG precedence order --
    the same file the desktop environment itself would resolve. Any basename
    containing one of `excluded_patterns` (case-insensitive) is dropped.
    """
    lowercased_exclusions = [pattern.lower() for pattern in (excluded_patterns or [])]
    discovered_by_basename: dict[str, Path] = {}

    for applications_directory in SYSTEM_APPLICATION_DIRECTORIES:
        if not applications_directory.is_dir():
            continue
        try:
            desktop_file_paths = sorted(applications_directory.glob("*.desktop"))
        except OSError:
            continue
        for desktop_file_path in desktop_file_paths:
            if desktop_file_path.name in discovered_by_basename:
                continue
            if any(pattern in desktop_file_path.name.lower() for pattern in lowercased_exclusions):
                continue
            if is_chromium_launcher(desktop_file_path):
                discovered_by_basename[desktop_file_path.name] = desktop_file_path

    return [discovered_by_basename[name] for name in sorted(discovered_by_basename)]


# --------------------------------------------------------------------------
# Rewriting
# --------------------------------------------------------------------------

def quote_for_desktop_exec(token: str) -> str:
    """Quote one Exec argument the way the Desktop Entry spec requires."""
    if token and not (DESKTOP_ENTRY_RESERVED_CHARACTERS & set(token)):
        return token
    escaped_token = token.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped_token}"'


def insert_flag_into_exec_command(exec_command_line: str) -> str:
    """Return the Exec value with the accessibility flag inserted.

    The flag goes after the program -- and, for Flatpak, after the application
    id, so it reaches the app rather than flatpak itself -- but before any field
    code, file-forwarding sentinel or literal URI argument.
    """
    if CHROMIUM_ACCESSIBILITY_FLAG in exec_command_line:
        return exec_command_line

    command_tokens = split_exec_value(exec_command_line)
    if not command_tokens:
        return exec_command_line

    insertion_index = len(command_tokens)
    for token_index, token in enumerate(command_tokens):
        if ARGUMENT_PLACEHOLDER_PATTERN.match(token):
            insertion_index = token_index
            break

    # Never insert as the program name itself.
    insertion_index = max(insertion_index, 1)
    command_tokens.insert(insertion_index, CHROMIUM_ACCESSIBILITY_FLAG)

    return " ".join(quote_for_desktop_exec(token) for token in command_tokens)


def build_override_contents(original_contents: str) -> tuple[str, int]:
    """Rewrite every Exec= line. Returns the new text and how many changed."""
    rewritten_lines: list[str] = []
    changed_exec_line_count = 0

    for line in original_contents.splitlines():
        if line.startswith("Exec="):
            original_exec_value = line[len("Exec="):]
            updated_exec_value = insert_flag_into_exec_command(original_exec_value)
            if updated_exec_value != original_exec_value:
                changed_exec_line_count += 1
            rewritten_lines.append(f"Exec={updated_exec_value}")
        else:
            rewritten_lines.append(line)

    # The marker goes after the [Desktop Entry] header: comments before the first
    # group header are legal but easy to lose to editors.
    for line_index, line in enumerate(rewritten_lines):
        if line.strip() == "[Desktop Entry]":
            rewritten_lines.insert(line_index + 1, GENERATED_MARKER_COMMENT)
            break

    return "\n".join(rewritten_lines) + "\n", changed_exec_line_count


# --------------------------------------------------------------------------
# Commands
# --------------------------------------------------------------------------

def command_list(excluded_patterns: list[str]) -> int:
    launchers = discover_chromium_launchers(excluded_patterns)
    if not launchers:
        print("No Chromium/Electron launchers detected.")
        return 0
    print(f"{len(launchers)} Chromium/Electron launcher(s) detected:")
    for launcher_path in launchers:
        print(f"  {launcher_path}")
    return 0


def command_apply(dry_run: bool, excluded_patterns: list[str]) -> int:
    launchers = discover_chromium_launchers(excluded_patterns)
    if not launchers:
        print("No Chromium/Electron launchers detected; nothing to do.")
        return 0

    if not dry_run:
        USER_APPLICATIONS_DIRECTORY.mkdir(parents=True, exist_ok=True)

    written_count = 0
    for source_launcher_path in launchers:
        destination_path = USER_APPLICATIONS_DIRECTORY / source_launcher_path.name

        if destination_path.exists():
            existing_contents = destination_path.read_text(encoding="utf-8", errors="replace")
            if not is_generated_by_this_script(existing_contents):
                print(
                    f"  REFUSE   {source_launcher_path.name}  (a user override already "
                    "exists and was not written by this script; not overwriting "
                    "hand-made configuration)"
                )
                continue

        original_contents = source_launcher_path.read_text(encoding="utf-8", errors="replace")
        override_contents, changed_exec_line_count = build_override_contents(original_contents)

        if changed_exec_line_count == 0:
            print(f"  skip     {source_launcher_path.name}  (already flagged)")
            continue

        verb = "would write" if dry_run else "wrote   "
        print(f"  {verb} {source_launcher_path.name}  ({changed_exec_line_count} Exec line(s))")
        if not dry_run:
            destination_path.write_text(override_contents, encoding="utf-8")
            destination_path.chmod(0o755)
        written_count += 1

    if dry_run:
        print(f"\nDry run: {written_count} file(s) would change. Re-run without --dry-run.")
        return 0

    if written_count:
        refresh_desktop_database()
        print(
            "\nDone. Already-running apps keep their old command line -- restart them, "
            "or log out and back in."
        )
    return 0


def command_revert() -> int:
    if not USER_APPLICATIONS_DIRECTORY.is_dir():
        print("Nothing to revert.")
        return 0

    removed_count = 0
    for candidate_path in sorted(USER_APPLICATIONS_DIRECTORY.glob("*.desktop")):
        contents = candidate_path.read_text(encoding="utf-8", errors="replace")
        if is_generated_by_this_script(contents):
            candidate_path.unlink()
            print(f"  removed  {candidate_path.name}")
            removed_count += 1

    if removed_count:
        refresh_desktop_database()
        print(f"\nRemoved {removed_count} generated override(s); packaged launchers apply again.")
    else:
        print("No generated overrides found; nothing removed.")
    return 0


def refresh_desktop_database() -> None:
    if shutil.which("update-desktop-database"):
        os.system(f"update-desktop-database {USER_APPLICATIONS_DIRECTORY} 2>/dev/null")


def main() -> int:
    argument_parser = argparse.ArgumentParser(
        description=(
            "Add --force-renderer-accessibility to Chromium/Electron .desktop "
            "launchers so AT-SPI can read their UI."
        )
    )
    mutually_exclusive = argument_parser.add_mutually_exclusive_group()
    mutually_exclusive.add_argument(
        "--list", action="store_true", help="detect Chromium/Electron launchers and exit"
    )
    mutually_exclusive.add_argument(
        "--dry-run", action="store_true", help="show what would change, write nothing"
    )
    mutually_exclusive.add_argument(
        "--revert", action="store_true", help="delete the overrides this script wrote"
    )
    argument_parser.add_argument(
        "--exclude",
        action="append",
        default=[],
        metavar="TEXT",
        help=(
            "skip launchers whose filename contains TEXT (case-insensitive); "
            "repeatable. Use this for an app that mis-detects or dislikes the flag."
        ),
    )
    parsed_arguments = argument_parser.parse_args()

    if parsed_arguments.list:
        return command_list(parsed_arguments.exclude)
    if parsed_arguments.revert:
        return command_revert()
    return command_apply(dry_run=parsed_arguments.dry_run, excluded_patterns=parsed_arguments.exclude)


if __name__ == "__main__":
    sys.exit(main())
